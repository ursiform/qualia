"""Regenerate browser contracts from the authored QTP and OpenAPI documents."""

from importlib import import_module
from pathlib import Path
import json
import sys

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "src"))
qualia = import_module("qualia")
output = "/** Generated by tools/schema.py; edit the authored JSON contracts. */\n"
for name in ("schema", "openapi"):
    definition = json.dumps(getattr(qualia, name)(), indent=2)
    output += f"const {name}Definition = {definition};\n"
    output += f"export function {name}() {{ return JSON.parse(JSON.stringify({name}Definition)); }}\n"
(root / "lib/schema.js").write_text(output)
